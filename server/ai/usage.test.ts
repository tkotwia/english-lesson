import { describe, expect, it } from 'vitest';
import { quotaDate } from './usage.ts';

describe('額度週期日期', () => {
  // Gemini 的每日額度在太平洋時間午夜重置,不是台灣時間午夜。
  // 用量若以台灣日期歸戶,畫面上的「今日用量」會和實際剩餘額度對不起來。
  it('台灣時間下午重置前,仍算在前一個太平洋日期', () => {
    // 台灣 11/20 10:00 = UTC 11/20 02:00 = 太平洋 11/19 18:00
    expect(quotaDate(new Date('2026-11-20T02:00:00Z'))).toBe('2026-11-19');
  });

  it('太平洋時間過了午夜,就進入新的額度週期', () => {
    // 台灣 11/20 17:00 = UTC 11/20 09:00 = 太平洋 11/20 01:00
    expect(quotaDate(new Date('2026-11-20T09:00:00Z'))).toBe('2026-11-20');
  });
});
